import XCTest
import Foundation
@testable import HUDController

final class V907BLEDIM2ProtocolTests: XCTestCase {
    func testFieldVerifiedPhysicalPowerSemanticsUseCapturedFrames() {
        XCTAssertEqual(
            BLEDIM2Protocol.power(true, sequence: 0x09),
            Data([0x55, 0xAA, 0x09, 0x80, 0x00, 0x01, 0x00, 0x89])
        )
        XCTAssertEqual(
            BLEDIM2Protocol.power(false, sequence: 0x0A),
            Data([0x55, 0xAA, 0x0A, 0x80, 0x00, 0x01, 0x01, 0x8B])
        )
    }

    func testCapturedPrimaryColorFramesMatchOfficialIOSCapture() {
        XCTAssertEqual(
            BLEDIM2Protocol.color(AmbientRGB(red: 255, green: 0, blue: 0), sequence: 0x0B),
            Data([0x55, 0xAA, 0x0B, 0x82, 0x00, 0x0C, 0x00, 0xFF, 0x00, 0x00, 0x00, 0x00, 0xFF, 0x00, 0x80, 0x00, 0x00, 0x00, 0x16])
        )
        XCTAssertEqual(
            BLEDIM2Protocol.color(AmbientRGB(red: 0, green: 255, blue: 0), sequence: 0x0C),
            Data([0x55, 0xAA, 0x0C, 0x82, 0x00, 0x0C, 0x00, 0x00, 0xFF, 0x00, 0x00, 0x00, 0xFF, 0x00, 0x80, 0x00, 0x00, 0x00, 0x17])
        )
        XCTAssertEqual(
            BLEDIM2Protocol.color(AmbientRGB(red: 0, green: 0, blue: 255), sequence: 0x0E),
            Data([0x55, 0xAA, 0x0E, 0x82, 0x00, 0x0C, 0x00, 0x00, 0x00, 0xFF, 0x00, 0x00, 0xFF, 0x00, 0x80, 0x00, 0x00, 0x00, 0x19])
        )
    }

    func testCapturedBrightnessEndpointsMatchOfficialIOSCapture() {
        XCTAssertEqual(
            BLEDIM2Protocol.brightness(0, sequence: 0x12),
            Data([0x55, 0xAA, 0x12, 0x88, 0x00, 0x06, 0x02, 0x00, 0x00, 0x00, 0x00, 0x00, 0xA1])
        )
        XCTAssertEqual(
            BLEDIM2Protocol.brightness(100, sequence: 0x28),
            Data([0x55, 0xAA, 0x28, 0x88, 0x00, 0x06, 0x02, 0xFF, 0x00, 0x00, 0x00, 0x00, 0xB6])
        )
    }

    func testChecksumIncludesHeaderSequenceCommandLengthAndPayload() {
        let frame = BLEDIM2Protocol.frame(sequence: 0x21, command: 0x88, payload: [0x02, 0x7E, 0x00, 0x00, 0x00, 0x00])
        let bytes = [UInt8](frame)
        XCTAssertEqual(bytes.last, UInt8(truncatingIfNeeded: bytes.dropLast().reduce(0) { $0 + Int($1) }))
    }
}
